//! Component and theme libraries: the starter set compiled into the crate,
//! seeding it into a library folder, and the one write path every library
//! edit takes, which snapshots the old text into `.history` first.
//!
//! A library folder holds `components/<Name>.tsx`, `themes/<name>.json`,
//! `library.json` (its settings: `settings.rs`), `.history/` (snapshots
//! named `<stem>.<unix-ms>.<ext>`, never pruned) and `.seeded`.
//!
//! `.seeded` lists the starter files already offered, one
//! `path<TAB>sha256 of the text last written` a line (`seed.rs`; a legacy
//! line has no tab and no hash). Each load, for every starter in the set:
//! - never offered: copied if absent;
//! - offered and deleted: stays deleted;
//! - the file still hashes to the recorded text: the user never edited it, so
//!   a newer starter text replaces it (the old text goes to `.history`) and
//!   the new hash is recorded;
//! - the file hashes to anything else: it is the user's, left alone, and the
//!   edit's hash is never recorded;
//! - a legacy line, or a file with no line: untouched only if the file equals
//!   a version the repo ever shipped (`shipped.rs`, regenerated by
//!   `bun run studio:hashes`), else left and kept hashless.
//!
//! A starter dropped from the set is neither updated nor deleted, and its
//! line stays. `--reset` rewrites every differing or missing starter file and
//! records the hashes.

