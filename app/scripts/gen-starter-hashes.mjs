// Regenerate app/studio-core/src/library/shipped.rs: the SHA-256 of every
// version of each starter file the repo has shipped (every blob in HEAD's
// history for that path) plus the working-tree text, so a starter edit can
// be added before it is committed. Run from anywhere: `bun run studio:hashes`
// in app/. Hashes are of the raw bytes, as `library::seed` hashes a file.
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const library = "app/studio-core/library";
const out = join(root, "app/studio-core/src/library/shipped.rs");

const git = (...args) => execFileSync("git", args, { cwd: root, maxBuffer: 64 * 1024 * 1024 });
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

// The starters compiled into the crate, as `library::seed` names them.
const starter = readFileSync(join(root, "app/studio-core/src/library/starter.rs"), "utf8");
const paths = [
  ...[...starter.matchAll(/library\/components\/(\w+)\.tsx/g)].map((m) => `components/${m[1]}.tsx`),
  ...[...starter.matchAll(/library\/themes\/([\w-]+)\.json/g)].map((m) => `themes/${m[1]}.json`),
].sort();

const rows = paths.map((rel) => {
  const repoPath = `${library}/${rel}`;
  const commits = git("log", "--reverse", "--format=%H", "--", repoPath).toString().split("\n").filter(Boolean);
  const hashes = [];
  for (const sha of commits) {
    let blob;
    try {
      blob = git("show", `${sha}:${repoPath}`);
    } catch {
      continue; // the commit that deleted the file
    }
    hashes.push(sha256(blob));
  }
  const worktree = join(root, repoPath);
  if (existsSync(worktree)) hashes.push(sha256(readFileSync(worktree)));
  return [rel, [...new Set(hashes)]];
});

const body = rows
  .map(
    ([rel, hashes]) =>
      // One hash fits rustfmt's single line; several go one to a line.
      `    (\n        "${rel}",\n        ${
        hashes.length === 1
          ? `&["${hashes[0]}"],\n`
          : `&[\n${hashes.map((h) => `            "${h}",\n`).join("")}        ],\n`
      }    ),\n`,
  )
  .join("");

writeFileSync(
  out,
  `//! Every version of each starter file the repo has shipped, as SHA-256 hex of
//! the file's bytes: a legacy \`.seeded\` line carries no hash, so a library
//! copy equal to one of these is known to be untouched. Generated by
//! \`bun run studio:hashes\` in app/ (git history plus the working tree); a
//! starter edit adds its hash here, and \`current_starters_are_in_the_table\`
//! fails until it does.

/// \`(library path, hashes)\`, oldest version first.
pub const SHIPPED: &[(&str, &[&str])] = &[
${body}];
`,
);
console.log(`wrote ${out}`);
