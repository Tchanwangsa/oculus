// Refresh docs/cli-reference.md from the binary’s clap tree, writing only changes.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { app, buildCli } from "./runtime.mjs";

const out = join(dirname(app), "docs", "cli-reference.md");
// Always rebuilt from the current sources, never read from `target/` as found:
// a `cargo test` or `cargo check` reruns the app's build script, and tauri-build
// then copies the staged sidecar (possibly older) over `target/<profile>/oculus`.
// `buildCli` deletes that file first. This writes nothing under `binaries/`.
const binary = process.env.OCULUS_BIN ?? buildCli();

// `--stdout` renders and returns before touching the data directory, so this
// works on a machine where the app has never run and no database exists.
const rendered = execFileSync(binary, ["docs", "--stdout"], {
  encoding: "utf8",
  maxBuffer: 32 * 1024 * 1024,
});

// The binary's own banner names `oculus docs`, which is how the copy in the
// data directory is written but not this one. Swap it for a banner that names
// the command a reader of *this* file would actually run.
const banner =
  "<!-- Generated by `bun run docs:cli` from the CLI's own help. Do not edit:\n" +
  "     change the CLI and regenerate, or the file will lie to whoever reads it. -->\n";
const body = rendered.startsWith("<!--")
  ? rendered.slice(rendered.indexOf("-->") + 3).replace(/^\n+/, "\n")
  : `\n${rendered}`;
const markdown = banner + body;

// Rewriting an identical file would show up as a dirty tree after every build.
if (existsSync(out) && readFileSync(out, "utf8") === markdown) {
  console.log("[docs] cli-reference.md already current");
} else {
  writeFileSync(out, markdown);
  console.log(`[docs] wrote ${out}`);
}
