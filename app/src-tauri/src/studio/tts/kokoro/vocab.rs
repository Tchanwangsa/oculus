/// The id of a phoneme character.
pub fn id(c: char) -> Option<i64> {
    VOCAB.iter().find(|(v, _)| *v == c).map(|&(_, id)| id)
}

pub fn contains(c: char) -> bool {
    id(c).is_some()
}
